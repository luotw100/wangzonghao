def ts(dt: datetime) -> int:
    return int(dt.replace(tzinfo=timezone.utc).timestamp())


def mkblock(date_str: str, hour: int, minute: int, convos: list[tuple[str, str]]) -> list[dict]:
    year, mon, day = map(int, date_str.split("-"))
    t = datetime(year, mon, day, hour, minute, 0, tzinfo=timezone.utc)
    msgs = []
    for sender, content in convos:
        msgs.append({
            "sender": sender,
            "accountName": "金牌老板陈" if sender == CHEN_ID else "雨儿爱唱歌",
            "timestamp": ts(t),
            "type": 0,
            "content": content,
        })
        t += timedelta(minutes=random.randint(1, 4), seconds=random.randint(5, 55))
    return msgs


