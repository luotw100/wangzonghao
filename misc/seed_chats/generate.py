def build() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    index = []
    for c in CONVS:
        s_id = c["streamer"]
        s_disp = STREAMERS[s_id]["display"]
        f_id = c["fid"]
        t = c["start"]
        messages = []
        for role, text, gap in c["msgs"]:
            t += gap
            messages.append({
                "sender": s_id if role == "S" else f_id,
                "timestamp": t,
                "type": 0,
                "content": text,
            })
        doc = {
            "chatlab": {"version": "1.0", "exportedAt": c["start"]},
            "meta": {
                "name": f"{c['name']}（与{s_disp}）",
                "platform": c["platform"],
                "type": "private",
                "ownerId": s_id,
                # 仅作人工核对，导入逻辑不读取以下两字段
                "_streamerStyle": STREAMERS[s_id]["desc"],
                "_fanProfile": c["profile"],
            },
            "members": [
                {"platformId": s_id, "accountName": s_id, "groupNickname": s_disp},
                {"platformId": f_id, "accountName": c["account"], "groupNickname": c["name"]},
            ],
            "messages": messages,
        }
        fname = f"{s_id}__{f_id}.json"
        (OUT / fname).write_text(
            json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        index.append((fname, s_disp, c["name"], c["profile"], len(messages)))

    lines = ["# seed_chats 索引（共 %d 段私聊，5 主播 × 3 粉丝）\n" % len(index)]
    cur = None
    for fname, s_disp, fan, prof, n in index:
        if s_disp != cur:
            cur = s_disp
            lines.append(f"\n## {s_disp} — {STREAMERS[[k for k,v in STREAMERS.items() if v['display']==s_disp][0]]['desc']}")
        lines.append(f"- `{fname}` · {fan} · {prof} · {n} 条")
    (OUT / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(index)} files -> {OUT}")


if __name__ == "__main__":
    build()
